#!/bin/sh
# Builds src/emblem-engine.js from em.c (Emblem's rule engine, unchanged) and emglue.c:
# clang to WebAssembly, then binaryen's wasm2js to plain JavaScript, so the page runs
# anywhere, GitHub Pages included, with no WebAssembly permission.
# Needs: clang with the wasm32 target, wasm-ld, and node (npx fetches binaryen once).
set -e
cd "$(dirname "$0")"
EXP=""
for f in glue_text glue_out glue_met glue_earned glue_load glue_step glue_stable glue_nshow glue_show_value glue_show_name; do
  EXP="$EXP -Wl,--export=$f"
done
clang --target=wasm32 -O2 -nostdlib -ffreestanding -fno-builtin -Ishim -I. \
  -Wl,--no-entry $EXP -Wl,--export-memory -Wl,--allow-undefined -Wl,-z,stack-size=65536 \
  -o /tmp/emblem.wasm em.c emglue.c
npx --yes -p binaryen@132.0.0 wasm2js /tmp/emblem.wasm -O2 -o /tmp/emblem.wasm.js
python3 - <<'PY'
s = open("/tmp/emblem.wasm.js").read()
s = s.replace("import * as env from 'env';\n", "")
s = s[: s.index("var retasmFunc")]
s = ("/* Emblem's rule engine (emblem/src/em.c, unchanged) + emglue.c, compiled with clang to\n"
     "   WebAssembly and turned into plain JavaScript by binaryen's wasm2js. Generated by\n"
     "   engine/build.sh: do not edit. */\nfunction emblemAsm(env) {\n" + s + "return asmFunc({ env: env });\n}\n")
open("../src/emblem-engine.js", "w").write(s)
PY
echo "src/emblem-engine.js: $(wc -c < ../src/emblem-engine.js) bytes"
